from dataclasses import dataclass

CLARIFY = "Clarify loop (runs inside the agent)"
CALENDAR = "Calendar port (separate MCP server)"


@dataclass(frozen=True)
class Tool:
    name: str
    group: str
    chosen_by: str
    purpose: str
    inputs: str
    output: str
    limits: str


MODEL_STEP = "The model, one step at a time"
CODE = "Plain code, never the model"

TOOLS: tuple[Tool, ...] = (
    Tool(
        name="get_listing",
        group=CLARIFY,
        chosen_by=MODEL_STEP,
        purpose="Read the item details the user pasted (title, description, category).",
        inputs="None: it reads this negotiation's own listing.",
        output="The listing as JSON, or a note that there is none.",
        limits="Read-only. Output cut to 1500 characters.",
    ),
    Tool(
        name="get_market_stats",
        group=CLARIFY,
        chosen_by=MODEL_STEP,
        purpose="Summarise the similar-item prices the user supplied.",
        inputs="None: it reads this negotiation's own comparables.",
        output="A one-line summary, or a note that there are no comparable prices.",
        limits="Read-only and informational: it never changes a price. Output cut to 1500 characters.",
    ),
    Tool(
        name="search_knowledge",
        group=CLARIFY,
        chosen_by=MODEL_STEP,
        purpose="Look up buying guidance for this kind of item in the knowledge base.",
        inputs="A short text query. The search covers the item's category plus general guidance.",
        output="The best matching passages joined into one text, or a note that none were found.",
        limits="Read-only vector search. Needs the knowledge base; otherwise it says so. "
        "Output cut to 1500 characters.",
    ),
    Tool(
        name="ask_seller",
        group=CLARIFY,
        chosen_by=MODEL_STEP,
        purpose="Send the seller one short question instead of an offer this turn.",
        inputs="The question text.",
        output="The question becomes the draft and goes through the same message checks as "
        "every message. A rejected question is replaced by a plain template.",
        limits="At most 2 questions per negotiation. Only when the seller gave no price or "
        "changed the terms. The prompt forbids numbers, budgets and limits in a question.",
    ),
    Tool(
        name="proceed",
        group=CLARIFY,
        chosen_by=MODEL_STEP,
        purpose="Stop planning. The buyer's normal reply is written next.",
        inputs="None.",
        output="None.",
        limits="At most 4 planning steps per turn, then planning stops by itself.",
    ),
    Tool(
        name="propose_slots",
        group=CALENDAR,
        chosen_by=CODE,
        purpose="List free pickup times.",
        inputs="How many slots, and optionally a start time.",
        output="ISO times: hourly slots from 10:00 to 19:00 Malaysia time, at least 24 hours ahead.",
        limits="Read-only.",
    ),
    Tool(
        name="book_slot",
        group=CALENDAR,
        chosen_by=CODE,
        purpose="Book a pickup time after a deal.",
        inputs="A booking key (the run id plus ':pickup'), the run id and the start time.",
        output="booked, already_booked, slot_taken or invalid.",
        limits="Idempotent: the same key never books twice. A booking failure never undoes the deal.",
    ),
    Tool(
        name="cancel_booking",
        group=CALENDAR,
        chosen_by=CODE,
        purpose="Cancel the pickup booked for a negotiation.",
        inputs="The booking key.",
        output="cancelled or not_found.",
        limits="Only reachable from the user's own action in the app.",
    ),
)


def render_markdown() -> str:
    lines = [
        "# Agent tools",
        "",
        "Generated by `scripts/render_tools_doc.py` from `backend/app/tools.py`.",
        "A test fails if this file is out of date.",
        "",
        "Rule for every tool: the model may pick a read-only step or write wording, and plain",
        "code validates and runs it. No tool lets the model set a price or see the budget.",
        "",
    ]
    for group in dict.fromkeys(tool.group for tool in TOOLS):
        lines += [
            f"## {group}",
            "",
            "| tool | chosen by | what it does | input | output | limits |",
            "|---|---|---|---|---|---|",
        ]
        lines += [
            f"| `{t.name}` | {t.chosen_by} | {t.purpose} | {t.inputs} | {t.output} | {t.limits} |"
            for t in TOOLS
            if t.group == group
        ]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"